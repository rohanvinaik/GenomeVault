"""
Alembic environment configuration for GenomeVault database migrations.

This module configures the Alembic migration environment with support for:
- Async database operations
- Automatic schema detection
- Partitioned tables for time-series data
- HIPAA-compliant audit logging
"""

import os
import sys
import logging
from logging.config import fileConfig
from pathlib import Path

from sqlalchemy import engine_from_config, pool, text
from sqlalchemy.ext.asyncio import AsyncEngine, create_async_engine
from alembic import context

# Add parent directory to path
sys.path.insert(0, str(Path(__file__).parent.parent.parent))

# Import GenomeVault models
from genomevault.models import Base
from genomevault.models.user import User, Role, Permission
from genomevault.models.audit import AuditLog, PHIAccessLog
from genomevault.models.genomic import GenomicDataMetadata, HypervectorStorage
