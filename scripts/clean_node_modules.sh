#!/bin/bash
set -e

echo "📦 Cleaning up vendored node_modules"
echo "===================================="

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

# Count tracked node_modules files
TRACKED_COUNT=$(git ls-files | grep -c "node_modules" || echo "0")
echo -e "${YELLOW}Found ${TRACKED_COUNT} node_modules files in git${NC}"

# Remove node_modules from git
echo "Removing node_modules from repository..."
git rm -r --cached zk_circuits/node_modules 2>/dev/null || true
git rm -r --cached zk_circuits/zk_circuits/node_modules 2>/dev/null || true

# Remove physical node_modules directories
echo "Removing node_modules directories..."
find . -type d -name "node_modules" -not -path "./venv/*" -not -path "./.venv/*" -exec rm -rf {} + 2>/dev/null || true

# Create proper package.json for zk_circuits
echo "Creating package.json for zk_circuits..."
cat > zk_circuits/package.json << 'EOF'
{
  "name": "genomevault-zk-circuits",
  "version": "1.0.0",
  "description": "Zero-knowledge circuits for GenomeVault",
  "private": true,
  "scripts": {
    "install": "npm ci",
    "compile": "bash ../scripts/compile_circuits.sh",
    "test": "mocha test/*.js",
    "benchmark": "node benchmark.js"
  },
  "dependencies": {
    "circomlib": "^2.0.5",
    "snarkjs": "^0.7.3",
    "circomlibjs": "^0.1.7",
    "circom_runtime": "^0.1.25",
    "ffjavascript": "^0.3.0",
    "r1csfile": "^0.0.48",
    "fastfile": "^0.0.20",
    "@iden3/binfileutils": "^0.0.12"
  },
  "devDependencies": {
    "mocha": "^10.2.0",
    "chai": "^4.3.10"
  }
}
EOF

# Create root package.json if it doesn't exist
if [ ! -f package.json ]; then
    echo "Creating root package.json..."
    cat > package.json << 'EOF'
{
  "name": "genomevault",
  "version": "0.1.0",
  "description": "Privacy-preserving genomic computing platform",
  "private": true,
  "workspaces": [
    "zk_circuits"
  ],
  "scripts": {
    "install": "npm ci",
    "install:circuits": "cd zk_circuits && npm ci",
    "compile:circuits": "cd zk_circuits && npm run compile",
    "test:circuits": "cd zk_circuits && npm test",
    "clean": "find . -name 'node_modules' -type d -prune -exec rm -rf {} +"
  },
  "engines": {
    "node": ">=16.0.0",
    "npm": ">=8.0.0"
  }
}
EOF
fi

# Update .gitignore if needed
echo "Updating .gitignore..."
if ! grep -q "^node_modules/$" .gitignore 2>/dev/null; then
    echo "" >> .gitignore
    echo "# Node.js dependencies - NEVER commit" >> .gitignore
    echo "node_modules/" >> .gitignore
    echo "**/node_modules/" >> .gitignore
    echo "npm-debug.log*" >> .gitignore
    echo "yarn-debug.log*" >> .gitignore
    echo "yarn-error.log*" >> .gitignore
    echo "package-lock.json" >> .gitignore
    echo "yarn.lock" >> .gitignore
fi

# Create installation script for users
echo "Creating installation helper script..."
cat > scripts/setup_circuits.sh << 'EOF'
#!/bin/bash
# Setup script for GenomeVault ZK circuits

set -e

echo "🔧 Setting up GenomeVault ZK Circuits"
echo "======================================"

# Check Node.js
if ! command -v node &> /dev/null; then
    echo "❌ Node.js is required but not installed."
    echo "Please install Node.js 16+ from: https://nodejs.org/"
    exit 1
fi

# Check npm
if ! command -v npm &> /dev/null; then
    echo "❌ npm is required but not installed."
    echo "Please install npm with Node.js"
    exit 1
fi

NODE_VERSION=$(node -v | cut -d'v' -f2 | cut -d'.' -f1)
if [ "$NODE_VERSION" -lt 16 ]; then
    echo "❌ Node.js 16+ is required (found: $(node -v))"
    exit 1
fi

echo "✅ Node.js $(node -v) detected"
echo "✅ npm $(npm -v) detected"

# Install dependencies
echo ""
echo "Installing circuit dependencies..."
cd zk_circuits
npm ci --production

# Check Circom
if ! command -v circom &> /dev/null; then
    echo ""
    echo "⚠️  Circom compiler not found"
    echo "To compile circuits, install Circom:"
    echo "  curl --proto '=https' --tlsv1.2 -sSf https://docs.circom.io/getting-started/installation/ | sh"
else
    echo "✅ Circom $(circom --version) detected"
fi

echo ""
echo "✅ ZK Circuits setup complete!"
echo ""
echo "Next steps:"
echo "  1. Compile circuits: cd zk_circuits && npm run compile"
echo "  2. Run tests: cd zk_circuits && npm test"
echo "  3. Run benchmarks: cd zk_circuits && npm run benchmark"
EOF

chmod +x scripts/setup_circuits.sh

# Count files to be removed
TOTAL_FILES=$(find . -path "*/node_modules/*" -type f | wc -l | tr -d ' ')

echo ""
echo -e "${GREEN}✅ Cleanup complete!${NC}"
echo ""
echo "Summary:"
echo "  - Removed ${TRACKED_COUNT} tracked node_modules files from git"
echo "  - Removed ${TOTAL_FILES} total node_modules files from disk"
echo "  - Created proper package.json files"
echo "  - Updated .gitignore"
echo "  - Created setup script"
echo ""
echo "Next steps:"
echo "  1. Review changes: git status"
echo "  2. Commit removal: git commit -m 'chore: remove vendored node_modules'"
echo "  3. Users run: ./scripts/setup_circuits.sh"
